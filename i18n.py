def t(key: str, **kw) -> str:
    """Translate `key` into the current language; falls back to the key itself."""
    pair = TEXT.get(key)
    if pair is None:
        return key
    s = pair[0 if st.session_state.get("lang", "ar") == "ar" else 1]
    return s.format(**kw) if kw else s
